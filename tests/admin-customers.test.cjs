const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const ts=require("typescript");
const root=path.resolve(__dirname,"..");
require.extensions[".ts"]=(module,file)=>module._compile(ts.transpileModule(fs.readFileSync(file,"utf8"),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,file);
const {buildAdminCustomers:build}=require("../src/lib/admin-customers.ts");
const profile={id:"account",first_name:"Ben",last_name:"Test",phone:"111",role:"customer",email:"BEN@example.com"};
const booking={id:"a",user_id:null,guest_first_name:"Guest",guest_last_name:"Test",guest_email:" ben@EXAMPLE.com ",guest_phone:"222",booking_date:"2026-11-12",booking_time:"8:00 AM",reference_code:"WOW-SYCWR9"};
const merged=build([profile],[booking]);
assert.equal(merged.length,1);
assert.equal(merged[0].id,"account");
assert.equal(merged[0].is_guest,false);
assert.deepEqual(merged[0].booking_ids,["a"],"guest booking attaches to the matching customer history");
assert.ok(merged[0].search_text.includes("wow-sycwr9"));
assert.equal(profile.email,"BEN@example.com","original account record isn't changed");
assert.equal(booking.user_id,null,"email grouping never changes booking ownership or auth access");
const first={...booking,guest_email:"guest@example.com"};
const second={...first,id:"b",booking_time:"2:00 PM",guest_first_name:"Latest",guest_phone:"333"};
const guest=build([], [first,second]);
assert.equal(guest.length,1);
assert.equal(guest[0].first_name,"Latest");
assert.equal(guest[0].phone,"333");
assert.deepEqual(guest[0].booking_ids,["b","a"]);
assert.equal(build([], [first,{...second,guest_email:"other@example.com"}]).length,2,"same phone or name doesn't merge different emails");
assert.equal(build([], [first,{...second,guest_email:null}]).length,2);
assert.equal(build([], [{...first,guest_email:null},{...second,guest_email:null}]).length,2,"missing emails stay distinct");
const other={...profile,id:"another-account",email:"other@example.com"};
const linked=build([profile,other],[{...booking,user_id:"account",guest_email:"other@example.com"}]);
assert.deepEqual(linked.find(c=>c.id==="account").booking_ids,["a"]);
assert.deepEqual(linked.find(c=>c.id==="another-account").booking_ids,[],"explicit ownership takes priority");
assert.equal(build([], [{...booking,archived_at:"2026-11-03"}]).length,0);
assert.equal(build([], [{...booking,archived_at:"2026-11-03"}],true).length,1);
assert.equal(build([profile],[]).length,1,"existing contacts remain even without bookings");
for(const file of ["src/lib/admin-customers.ts","src/app/admin/page.tsx"]){
 const result=ts.transpileModule(fs.readFileSync(path.join(root,file),"utf8"),{fileName:file,compilerOptions:{jsx:ts.JsxEmit.ReactJSX,module:ts.ModuleKind.ESNext},reportDiagnostics:true});
 assert.deepEqual((result.diagnostics||[]).filter(d=>d.category===ts.DiagnosticCategory.Error),[],file);
}
console.log("Customer email grouping, booking ownership, guest history, archive visibility and search checks passed.");
